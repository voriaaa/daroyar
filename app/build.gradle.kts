android {
    namespace = "ir.daroyar.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "ir.daroyar.app"
        // java.time is available from Android 8.0 (API 26) without desugaring.
        minSdk = 26
        targetSdk = 35
        // CI passes an increasing VERSION_CODE (GitHub run number); stores require it to grow on every update.
        versionCode = (System.getenv("VERSION_CODE") ?: "1").toInt()
        versionName = System.getenv("VERSION_NAME") ?: "1.0.0"
        vectorDrawables { useSupportLibrary = true }
    }

    // Release signing: values come from environment variables (GitHub Secrets in CI),
    // so the keystore and passwords are never stored in the repository.
    val keystorePath = System.getenv("DAROYAR_KEYSTORE_PATH")
    signingConfigs {
        if (keystorePath != null && file(keystorePath).exists()) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("DAROYAR_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("DAROYAR_KEY_ALIAS")
                keyPassword = System.getenv("DAROYAR_KEY_PASSWORD")
                enableV1Signing = true
                enableV2Signing = true
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    lint {
        checkReleaseBuilds = false
        abortOnError = false
    }

    packaging {
        resources { excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    }
