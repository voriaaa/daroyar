package ir.daroyar.app.drugs

/**
 * Built-in, offline reference of common drugs in Iran. Texts are short, general summaries for
 * patients; they are not a substitute for the prescriber's or pharmacist's instructions.
 *
 * Split into groups so no single initializer exceeds the JVM method size limit.
 */
object DrugDatabase {

    val drugs: List<Drug> by lazy {
        painDrugs() + heartDrugs() + diabetesAndHormoneDrugs() + stomachDrugs() +
            antibiotics() + mindAndNerveDrugs() + allergyAndLungDrugs() + supplements() + vitaminsAndHerbals() + otherDrugs()
    }

    val byId: Map<String, Drug> by lazy { drugs.associateBy { it.id } }

    /** Brand or common names of combination products, mapped to every drug they contain. */
    val combos: Map<String, List<String>> = mapOf(
        "فروفولیک" to listOf("iron", "folic_acid"),
        "فرفولیک" to listOf("iron", "folic_acid"),
        "کلسیم د" to listOf("calcium", "vitamin_d"),
        "کلسیم دی" to listOf("calcium", "vitamin_d"),
        "لوزارتان اچ" to listOf("losartan", "hydrochlorothiazide"),
        "losartan h" to listOf("losartan", "hydrochlorothiazide"),
        "نوافن" to listOf("acetaminophen", "ibuprofen"),
        "novafen" to listOf("acetaminophen", "ibuprofen"),
        "سینمت" to listOf("levodopa"),
    )
}

private fun t(h: Int, m: Int = 0) = h * 60 + m

